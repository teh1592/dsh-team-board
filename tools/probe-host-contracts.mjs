import { pathToFileURL } from 'node:url';
import path from 'node:path';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import assert from 'node:assert/strict';
import { DshCommandRunner } from '../host/dsh/command-runner.mjs';
import { FileRunStore } from '../host/dsh/file-store.mjs';
import { createRun } from '../src/review/state.mjs';
import { outputSchema } from '../src/review/schemas.mjs';
import { installReview, installStageToolPolicy } from '../host/review-plugin.mjs';
import { ReviewService } from '../host/review-service.mjs';
import { registerReviewTools, submitDefinition } from '../host/dsh/tools.mjs';
const runtime = process.argv[2];
if (!runtime) throw new Error('Usage: node tools/probe-host-contracts.mjs <installed-dsh-directory>');
const load = async (packageName) => import(pathToFileURL(path.join(runtime, 'node_modules', '@deepseek-ai', packageName, 'lib', 'index.js')).href);
const [{ Context }, { default: Subprocess }, { default: FileSystem }, { default: Tools, assertSupportedJsonSchema }, { default: SystemPrompt }, { createScope }, { snapshotJsonValue }] = await Promise.all([load('cordis'), load('dsh-subprocess-local'), load('dsh-fs-local'), load('dsh-tools'), load('dsh-system-prompt'), load('dsh-scope'), load('dsh-util-values')]);
const ctx = new Context();
const projectRoot = await mkdtemp(path.join(os.tmpdir(), 'review-real-host-'));
let runner; let scope;
try {
  new Subprocess(ctx);
  const fs = new FileSystem(ctx, { cwd: projectRoot, diffBasisMaxBytes: 10485760 });
  const store = new FileRunStore(fs, projectRoot);
  await store.initialize();
  const run = createRun({ runId: 'host-probe', requestId: 'host-probe', requestDigest: 'd', rootSessionId: 'probe-root', projectRoot, requirement: 'Test installed public services' });
  await store.create(run);
  await store.commit(run.runId, 0, { operationId: 'update', request: 'update', apply(next) { next.status = 'paused'; return 'paused'; } });
  assert.equal((await store.load(run.runId)).status, 'paused');
  console.log('REAL_FS atomic RunStore create/commit/load: PASS');
  runner = new DshCommandRunner(ctx.subprocess);
  const result = await runner.run({ id: 'real-node', argv: [process.execPath, '-e', 'console.log(JSON.stringify({reviewProbe:true,node:process.version}))'], cwd: projectRoot, timeoutMs: 10000 });
  assert.equal(result.outcome, 'passed', JSON.stringify(result));
  assert.match(result.stdout, /reviewProbe/);
  console.log(`REAL_SUBPROCESS ${JSON.stringify(result)}`);
  new SystemPrompt(ctx, { includeHarnessIdentity: false, includeRuntimeContext: false, personaPrefix: '', personaSuffix: '', toolOrder: ['<unlisted-tools>'] });
  new Tools(ctx);
  const definition = (name) => ({ name, description: name, parameters: { type: 'object', properties: {}, additionalProperties: false }, output: { schema: { type: 'object', additionalProperties: true }, render: () => [] }, async execute() { return {}; } });
  ctx.tools.register(definition('read')); ctx.tools.register(definition('write'));
  const key = {};
  scope = createScope(ctx, key);
  scope.ctx.tools.register(definition('structured_output'));
  scope.ctx.tools.restrict({ allow: ['read'] });
  assert.deepEqual(ctx.tools.definitions().map((tool) => tool.name), ['read', 'write']);
  assert.deepEqual(ctx.tools.definitions(key).map((tool) => tool.name), ['read', 'structured_output']);
  assertSupportedJsonSchema(outputSchema('review'));
  console.log('REAL_TOOLS global definitions/restriction/scoped structured_output and schema: PASS');
  const policyCtx = new Context();
  try {
    new SystemPrompt(policyCtx, { includeHarnessIdentity: false, includeRuntimeContext: false, personaPrefix: '', personaSuffix: '', toolOrder: ['<unlisted-tools>'] });
    new Tools(policyCtx); policyCtx.tools.register(definition('research'));
    const presetKey = {}; const presetScope = createScope(policyCtx, presetKey);
    for (const name of ['read', 'write', 'edit', 'pwsh', 'review_start']) presetScope.ctx.tools.register(definition(name));
    const rootKey = {}; const rootScope = createScope(policyCtx, rootKey, { parent: presetKey });
    const visible = (key) => policyCtx.tools.definitions(key).map((tool) => tool.name).sort();
    const rootBefore = visible(rootKey); const presetBefore = visible(presetKey);
    for (const stageId of ['build', 'review', 'verify']) {
      const agent = { id: `policy-${stageId}` }; const childScope = createScope(policyCtx, agent, { parent: rootKey }); agent.ctx = childScope.ctx;
      childScope.ctx.tools.register(definition('structured_output'));
      childScope.ctx.tools.register(definition('local_extra'));
      const disposePolicy = installStageToolPolicy(policyCtx, agent, stageId);
      try {
        const names = visible(agent);
        assert.ok(names.includes('read'), `${stageId} must retain inherited preset read`);
        for (const name of ['write', 'edit', 'pwsh']) assert.equal(names.includes(name), stageId === 'build', `${stageId} visibility of ${name}`);
        assert.ok(names.includes('structured_output')); assert.equal(names.includes('review_start'), false);
        for (const name of ['write', 'edit', 'pwsh']) assert.equal(childScope.ctx.tools.checkGuards({ agent, name }) === undefined, stageId === 'build');
        assert.equal(childScope.ctx.tools.checkGuards({ agent, name: 'read' }), undefined);
        assert.equal(childScope.ctx.tools.checkGuards({ agent, name: 'structured_output' }), undefined);
        assert.ok(childScope.ctx.tools.checkGuards({ agent, name: 'review_start' }));
        assert.ok(names.includes('local_extra'), 'own tool remains registered');
        assert.ok(childScope.ctx.tools.checkGuards({ agent, name: 'local_extra' }), 'guard denies non-role own tool');
        assert.deepEqual(visible(rootKey), rootBefore); assert.deepEqual(visible(presetKey), presetBefore);
      } finally { disposePolicy(); await childScope.dispose(); }
    }
    await rootScope.dispose(); await presetScope.dispose();
    console.log('REAL_PRESET_TOOLS ancestor preset build read/write, review/verify read-only, own output and root isolation: PASS');
  } finally { await policyCtx.fiber.dispose(); }
  const service = new ReviewService({ store, agentRunner: {}, commandRunner: runner, isRootOnline: () => false });
  const captured = [];
  registerReviewTools({ tools: { register(definition) { captured.push(definition); return () => {}; } } }, async () => service, () => true);
  const call = async (name, args) => {
    const value = await captured.find((definition) => definition.name === name).execute(args, { agent: { id: 'probe-root' } });
    snapshotJsonValue(value); return value;
  };
  const started = await call('review_start', { requestId: 'json-output', requirement: 'Validate JSON', materials: [{ name: 'material', content: 'body' }] });
  await service.wait(started.runId);
  await call('review_status', { runId: started.runId });
  for (const section of ['run', 'report', 'executions', 'findings', 'decisions', 'tasks', 'checks', 'history', 'questions', 'diagnostics']) await call('review_read', { runId: started.runId, section });
  await call('review_control', { runId: started.runId, action: 'stop', operationId: 'json-stop' });
  await call('review_revise', { runId: started.runId, operationId: 'json-revise', requirement: 'Validate JSON again', reason: 'Probe revision' });
  await service.wait(started.runId);
  snapshotJsonValue(await service.probe(started.runId));
  const submit = submitDefinition({ async submit() { return { executionId: 'exec', applicability: 'current', duplicate: false }; } }, started.runId, 'exec', 'child');
  snapshotJsonValue(await submit.execute({ result: { executionId: 'exec' } }, { agent: { id: 'child' } }));
  await service.dispose();
  console.log('REAL_JSON_SNAPSHOT all five review tools, optional run fields, submit and probe: PASS');
  const disposeReview = installReview(ctx);
  assert.equal(ctx.tools.get('review_start'), undefined);
  const ready = () => new Promise((resolve) => setImmediate(resolve));
  const stopSubagents = ctx.provide('subagents', {});
  let stopAgents = ctx.provide('agents', { roots: () => [] });
  const stopDirectory = ctx.provide('workingDirectory', { get: () => projectRoot });
  await ready();
  assert.ok(ctx.tools.get('review_start'));
  await stopAgents();
  assert.equal(ctx.tools.get('review_start'), undefined);
  stopAgents = ctx.provide('agents', { roots: () => [] });
  await ready();
  assert.ok(ctx.tools.get('review_start'));
  await disposeReview();
  assert.equal(ctx.tools.get('review_start'), undefined);
  await stopAgents(); await stopDirectory(); await stopSubagents();
  console.log('REAL_CORDIS review delayed injection, dependency withdrawal/restoration and disposal: PASS');
} finally {
  await runner?.dispose();
  await scope?.dispose();
  await ctx.fiber.dispose();
  await rm(projectRoot, { recursive: true, force: true });
}
