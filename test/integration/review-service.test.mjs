test('pause waits at a stage boundary, resume reuses current output; cancel releases activation', async (t) => {
  const reached = deferred();
  const { service, store, runner } = await fixture(t, { hold: (spec) => { if (spec.stageId === 'intake') { reached.resolve(); return true; } return false; } });
  const { runId } = await service.start(request, actor);
  await reached.promise;
  await service.control(runId, 'pause', { operationId: 'pause-1' });
  let run = await store.load(runId);
  const intake = run.executions[0];
  const handle = runner.handles[0];
  const envelope = { schemaVersion: 1, executionId: intake.executionId, requirementRevision: 1, decisionRevision: 0, inputFingerprint: intake.inputFingerprint, kind: 'intake', result: { summary: 'intake done', acceptance: ['test'], questions: [] } };
  handle.resolve({ raw: { stopReason: 'completed', structured: envelope, output: [] }, envelope });
  await service.wait(runId);
  run = await store.load(runId); assert.equal(run.status, 'paused');
  await service.control(runId, 'resume', { operationId: 'resume-1' }); await service.wait(runId);
  run = await store.load(runId); assert.equal(run.status, 'completed');
  assert.equal(runner.calls.filter((call) => call.stageId === 'intake').length, 1);
  const second = await service.start({ ...request, requestId: 'cancel-request' }, actor);
  // Resolve start acceptance before cancelling; this wait is event-driven rather than a timer.
  await new Promise((resolve) => setImmediate(resolve));
  await service.control(second.runId, 'cancel', { operationId: 'cancel-1' });
  assert.equal((await store.load(second.runId)).status, 'cancelled');
  assert.ok(runner.handles.at(-1).cancelled);
});
test('waiting user choice is saved and user command continues; model identity cannot impersonate choice', async (t) => {
  const { service, store } = await fixture(t, { questions: true });
  const { runId } = await service.start(request, actor); await service.wait(runId);
  assert.equal((await store.load(runId)).status, 'waiting_user');
  await assert.rejects(service.decide(runId, 'Q-1', 'retry', { kind: 'model', sessionId: 'root' }, 'bad'), { code: 'USER_COMMAND_REQUIRED' });
  await service.decide(runId, 'Q-1', 'retry', { kind: 'user', sessionId: 'root' }, 'user-choice-1');
  await service.wait(runId);
  const run = await store.load(runId);
  assert.equal(run.status, 'completed'); assert.equal(run.questions[0].answer, 'retry');
  assert.equal(run.decisions[0].owner, 'user:root');
  assert.equal(run.executions.filter((execution) => execution.stageId === 'decide').length, 2);
  assert.ok(run.tasks.length > 0);
  assert.ok(run.decisions.at(-1).checks.length > 0);
});
test('storage serializes progress, rejects stale revisions and preserves state on failed atomic publication', async (t) => {
  const { store, projectRoot, setBeforePublish } = await fixture(t);
  const run = createRun({ runId: 'storage-run', requestId: 'storage', requestDigest: 'digest', rootSessionId: 'root', projectRoot, requirement: 'x' });
  await store.create(run);
  const operation = (id) => ({ operationId: id, request: id, apply(next) { next.summary = id; return id; } });
  const [a, b] = await Promise.all([store.commit(run.runId, undefined, operation('a')), store.commit(run.runId, undefined, operation('b'))]);
  assert.equal(a.run.revision, 1); assert.equal(b.run.revision, 2);
  await assert.rejects(store.commit(run.runId, 0, operation('c')), { code: 'REVISION_CONFLICT' });
  assert.equal((await store.commit(run.runId, 0, operation('a'))).replayed, true);
  setBeforePublish(async () => { throw new Error('disk publication failed'); });
  await assert.rejects(store.commit(run.runId, 2, operation('d')), /disk publication failed/);
  assert.equal((await store.load(run.runId)).revision, 2);
  assert.equal(JSON.parse(await readFile(`${projectRoot}/.review/runs/storage-run/run.json`, 'utf8')).summary, 'b');
  await assert.rejects(store.readArtifact(run.runId, '../secret'), { code: 'INVALID_REFERENCE' });
});
test('reload restores saved output and marks lost activation interrupted; retry drains old child before replacement', async (t) => {
  const { store, projectRoot } = await fixture(t);
  const run = createRun({ runId: 'recover-run', requestId: 'recover', requestDigest: 'digest', rootSessionId: 'root', projectRoot, requirement: 'x' });
  const execution = beginExecution(run, { stageId: 'intake', role: 'lead', executionId: 'lost', inputFingerprint: 'f' });
  execution.childSessionId = 'old-child';
  await store.create(run);
  const runner = automaticAgents(); const order = [];
  runner.stopRecovered = async () => { order.push('drained'); };
  const start = runner.start;
  runner.start = async (spec) => { order.push('started'); return start(spec); };
  const restored = new ReviewService({ store, agentRunner: runner }); t.after(() => restored.dispose());
  await restored.recover();
  const interrupted = await store.load(run.runId);
  assert.equal(interrupted.status, 'paused'); assert.equal(interrupted.executions[0].workStatus, 'interrupted');
  await restored.control(run.runId, 'retry', { operationId: 'retry' }); await restored.wait(run.runId);
  assert.equal(order[0], 'drained'); assert.equal(order[1], 'started');
  assert.equal((await store.load(run.runId)).status, 'completed');
  assert.equal((await store.load(run.runId)).executions[1].attempt, 2);
});
