import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { ReviewService } from '../../host/review-service.mjs';
import { createRun, beginExecution } from '../../src/review/state.mjs';
import { testStore, automaticAgents, deferred } from './helpers.mjs';
const request = { requestId: 'request-1', requirement: 'Add timeout handling', materials: [{ name: 'API contract', content: 'Timeout must clear pending state and preserve error.' }] };
const actor = { sessionId: 'root' };
async function fixture(t, options = {}) {
  const disk = await testStore(); t.after(() => disk.cleanup());
  const runner = automaticAgents(options);
  const notices = [];
  const service = new ReviewService({ store: disk.store, agentRunner: runner, notifier: { async enqueue(root, notice) { notices.push({ root, notice }); return `message-${notices.length}`; } } });
  t.after(() => service.dispose());
  return { ...disk, runner, service, notices };
}
test('start returns before completion, repeated request is one run; two independent reviews create traceable decisions and report', async (t) => {
  const { service, runner, store, notices } = await fixture(t);
  const first = await service.start(request, actor);
  assert.equal(first.status, 'queued');
  const duplicate = await service.start(request, actor);
  assert.equal(duplicate.runId, first.runId);
  await service.wait(first.runId);
  const run = await store.load(first.runId);
  assert.equal(run.status, 'completed', JSON.stringify(run));
  assert.equal((await store.list()).length, 1);
  assert.equal(runner.calls.length, 4);
  const reviews = runner.calls.filter((call) => call.stageId === 'review');
  assert.equal(reviews.length, 2);
  assert.notEqual(reviews[0].executionId, reviews[1].executionId);
  assert.deepEqual(reviews[0].inputs, reviews[1].inputs);
  assert.equal(reviews[0].inputs.reviews, undefined);
  assert.ok(reviews.every((call) => call.prompt.includes(request.materials[0].content)));
  assert.equal(run.findings.length, 2);
  assert.deepEqual(new Set(run.decisions[0].findingIds), new Set(run.findings.map((finding) => finding.id)));
  assert.equal(run.tasks.length, 1); assert.equal(run.tasks[0].decisionIds[0], '1:D-1');
  const report = await service.inspect(run.runId, 'report');
  assert.match(report.content, /Timeout and cancellation test/);
  assert.match(report.content, /Timeout may leave pending state/);
  assert.match(report.content, /D-1/);
  assert.ok(run.reportRef); assert.match(await store.readArtifact(run.runId, run.reportRef), /后续实施要求/);
  assert.equal(notices.length, 1);
  await service.notify(run.runId); assert.equal(notices.length, 1);
  assert.ok(runner.handles.every((handle) => handle.cancelled));
  await assert.rejects(service.start({ ...request, requirement: 'different' }, actor), { code: 'REQUEST_CONFLICT' });
});
